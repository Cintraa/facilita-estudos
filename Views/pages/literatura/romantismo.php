			<br>
			<subtitle>Características Gerais:</subtitle>
			<br>
			<p><topic>Idealização:</topic> Visão idealizada (imaginada, belo, perfeito) da vida, do amor, da mulher e da morte.</p>
			<br>
			<p><topic>Paixão Exacerbada:</topic> O sentimentalismo está acima de tudo, ocupa inteiramente o espírito do poeta.</p>
			<br>
			<p><topic>Natureza:</topic> Projeta o estado de espírito do poeta, que expressa toda sua paixão na natureza, reflete as angústias do eu lírico.</p>
			<br>
			<img src="<?php echo INCLUDE_PATH_IMG; ?>locus-horrendus.jpg" alt="locus-horrendus">
			<br>
			<p><topic>Nacionalismo:</topic> Valorização da terra natal, sentimento de união nacional e luta pela liberdade.</p>
			<br>
			<p><topic>Individualismo/egocentrismo:  :</topic>  O poeta coloca suas emoções, seu talento, sua arte acima de tudo.</p>
			<br>		
			<p><topic>Medievalismo:</topic> Característica da <de>primeira geração romântica</de>, resgate do cenário medieval gótico, do heroísmo do cavaleiro andante e de sua luta contra os árabes, idealizava o cavaleiro medieval. <de>Romance histórico</de>: narrativa ficcional que se ambienta no passado.</p>
			<br>
			<p><topic>Código de honra do cavaleiro (valores cristãos):</topic> </p>
			<br>
			<ul>
				<li>Bravura</li>
				<li>Fé</li>
				<li>Lealdade</li>
				<li>Castidade</li>
				<li>Intercessão</li>
				<li>Honestidade</li>
				<li>Integridade</li>
				<li>Caridade</li>
			</ul>
			<br>	
			<p><topic>Saudosismo:</topic> A infância e a adolescência são idealizadas como um tempo perdido e impossível de voltar, em oposição.</p>
			<br>
			<p><topic>Escapismo:</topic> O eu lírico romântico foge para sua imaginação, para o mundo dos sonhos, dos devaneios, fantasias.</p>
			<br>
			<p><topic>Spleen:</topic> O mal-do-século: tédio, depressão, melancolia que em algum momento o romântico sente​. Leva o nome do órgão baço, pois naquela época acreditava-se que ele produzia o hormônio da tristeza.</p>
			<br>
			<p><topic>Morbidez:</topic> O romântico aprecia estados doentios e a própria morte (<de>caráter gótico</de>).  “A morte de uma mulher bela é, sem sombra de dúvida, o tema mais poético do mundo.”</p>
			<br>
			<p><topic>Espírito noctívago:</topic> O romântico é boêmio e apaixonado por ambientes lúgubres (macabros), que traduzem sua alma, gostam de vagar à noite (noctívagos).</p>
			<br>
			<p><topic>Autocomiseração:</topic> Pena de si mesmo, “coitado de mim”.</p>
			<br>
			<p><topic>Ciclotimia lírica:</topic> Desequilíbrio emocional, bipolares emocionais, constantes mudanças de humor.</p>
			<br>
