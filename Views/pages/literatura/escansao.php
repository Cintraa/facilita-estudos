			<hgroup class="title"><h1><span>Escansão</span></h1></hgroup>
			<br>
			<ul>
				<topic>Conceito:</topic> Ferramenta para fazer a contagem das sílabas poéticas, empregada para saber a métrica (tamanho do verso), que é fixa.
				<br>
				<topic>Verso Livre:</topic> Não possui uma métrica fixa (ex: modernismo).
				<br>
				<topic>Ritmo:</topic>  Musicalidade provocada pela alternância de sílabas tônicas e átonas.
			</ul>
			<br>
			<subtitle>Regras:</subtitle>
			<br>
			<ol>
				<li>Conta-se até a sílaba tônica da última palavra. <de>Exemplos</de>: túmulo - contar até tú; rodapé - contar até pé.</li>
				<li> Ocorrem fusões de vogais entre palavras próximas, quando a palavra termina em vogal e a próxima seguinte começa em vogal contamos somente uma sílaba (chamado elisão na pronúncia). <de>Exemplos</de>: Toca o sino pequenino - To/<de>ca o</de>/si/no/pe/que/ni/<s>no</s>; Estava cansado e estanque - Can/sa/<de>do e es</de>/tan/<s>que</s>.</li>
			</ol>
			<br>
			<p><topic>Excessões:</topic></p>
			<br>
			<ul>
				<li>Quando uma palavra terminar por ditongo (encontro de duas vogais na mesma sílaba) e a próxima se iniciar por vogal, não ocorre fusão entre elas. <de>Exemplo</de>: Isso dói e me angustia - Is/so/<de>dói</de>/<de>e</de>/me an/gus/ti/<s>a</s>;</li>
				<br>
				<li>A seguna regra não ocorre quando há uma vírgula entre a fusão das vogais ou um monossílabo tônico (uma sílaba, tônica, ex: tu);</li>
				<br>
				<li>H não é proncunciado, e portanto, ignora-se.</li>
			</ul>
			<br>
			<subtitle>Classificação Métrica:</subtitle>
			<br>
			<ul>
				<li><b>5 sílabas:</b>  pentassílabo ou redondilha menor;</li>
				<li><b>6 sílabas:</b>  hexassílabo;</li>
				<li><b>7 sílabas:</b>  heptassílabo ou redondilha maior;</li>
				<li><b>8 sílabas:</b>  octossílabo;</li>
				<li><b>9 sílabas:</b>  eneassílabo;</li>
				<li><b>10 sílabas:</b> decassílabo ou medida nova;</li>
				<li><b>11 sílabas:</b> hendecassílabo ou undecassílabo;</li>
				<li><b>12 sílabas:</b> dodecassílabo ou alexandrino.</li>
				<br>
				<de>Os mais importantes e usados são: <b>5, 7, 10  e 12</b>.</de>
			</ul>	
