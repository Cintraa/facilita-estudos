				<li>Ocorre em células haplóides e diploides;</li>
				<li>Divisão realizada para crescimento, reposição de células e reparação de tecidos em seres pluricelulares e para reprodução em unicelulares;</li>
				<li>O câncer está relacionado a erros na mitose.</li>
			</ul>
