				<p>Quis um favor <i class="fas fa-long-arrow-alt-right"></i> Qui-<de>lo</de>.</p>
				<p>Fiz a tarefa <i class="fas fa-long-arrow-alt-right"></i> Fi-<de>la</de>.</p>
			</ol>
